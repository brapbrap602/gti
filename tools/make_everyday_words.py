"""Build novel-translate's everyday_words.txt from jieba's dictionary.

Name discovery drops a candidate that is, as a whole, an everyday word: one that
jieba's general dictionary counts at least MIN_FREQ times, or tags as an idiom or
set phrase, and does not tag as a proper noun. Only whole words are dropped, so a
name built from everyday words (世界树, 赤色帝国) stays a candidate.

    uv run python tools/make_everyday_words.py path/to/jieba/dict.txt

The dictionary is jieba v0.42.1's `jieba/dict.txt` (MIT License, Copyright (c) 2013 Sun Junyi):
https://raw.githubusercontent.com/fxsjy/jieba/v0.42.1/jieba/dict.txt
"""

import sys
from pathlib import Path

MIN_FREQ = 500
PROPER = {"nr", "ns", "nt", "nz", "nrt", "nrfg"}  # person, place, organisation and other proper nouns
SET_PHRASES = {"i", "l"}  # idioms (成语) and fixed expressions
OUT = Path(__file__).resolve().parent.parent / "packages/novel-translate/src/novel_translate/everyday_words.txt"


def everyday(lines: list[str]) -> list[str]:
    words = set()
    for line in lines:
        word, freq, tag = line.split()
        if len(word) >= 2 and tag not in PROPER and (int(freq) >= MIN_FREQ or tag in SET_PHRASES):
            words.add(word)
    return sorted(words)


def main(dictionary: Path) -> None:
    words = everyday(dictionary.read_text(encoding="utf-8").splitlines())
    header = [
        "# Everyday words: discovery drops a candidate that is exactly one of these.",
        f"# Generated by tools/make_everyday_words.py (frequency >= {MIN_FREQ}, or an idiom or set phrase; no proper nouns)",
        "# from jieba v0.42.1's dict.txt, MIT License, Copyright (c) 2013 Sun Junyi.",
    ]
    OUT.write_text("\n".join(header + words) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(words)} words -> {OUT}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
